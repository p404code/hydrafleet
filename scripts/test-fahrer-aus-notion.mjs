import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const basis = process.env.PGLITE;
if (!basis) { console.error('PGLITE fehlt – siehe Kopf dieser Datei.'); process.exit(2); }
const { PGlite } = await import(pathToFileURL(join(basis, 'node_modules/@electric-sql/pglite/dist/index.js')).href);
const db = new PGlite();

await db.exec(`
create role anon; create role authenticated;
create schema auth;
create function auth.jwt() returns jsonb language sql stable as $$
  select nullif(current_setting('request.jwt.claims', true), '')::jsonb $$;
create function public.is_app_user() returns boolean language sql stable as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'app_role') in ('admin','user'), false) $$;
create function public.tel_key(t text) returns text language sql immutable as $$
  select case when d like '00%' then substr(d, 3) when d like '0%' then '43' || substr(d, 2) else d end
  from (select regexp_replace(coalesce(t, ''), '[^0-9]', '', 'g') as d) x $$;
create function public.name_key(t text) returns text language sql immutable as $$
  select coalesce((select string_agg(w, ' ' order by w)
    from unnest(string_to_array(lower(regexp_replace(coalesce(t, ''), '[^a-zA-Z]', ' ', 'g')), ' ')) w where w <> ''), '') $$;
create table public.fahrer (id integer generated by default as identity primary key, name text not null, telefon text,
  kennzeichen text, mietmodell text default 'fix' check (mietmodell in ('fix','f11','f12')), basis_miete numeric default 450,
  prozent_satz numeric default 0, prozent_schwelle numeric default 1200, aktiv boolean default true, notion_fahrer_id integer);
create table public.notion_fahrer (notion_page_id text primary key, notion_fahrer_id integer, name text, telefon text,
  status text, firma text);
create table public.bolt_drivers (driver_uuid text primary key, fahrer_id integer, zuordnung_quelle text);
create table public.uber_drivers (driver_uuid text primary key, fahrer_id integer, zuordnung_quelle text);
create table public.zuordnung_manuell (anbieter text not null, driver_uuid text not null, notion_fahrer_id integer not null,
  gesetzt_von text not null, gesetzt_am timestamptz default now(), primary key (anbieter, driver_uuid));
create function public.konto_zuordnen(p_anbieter text, p_driver_uuid text, p_fahrer_id integer) returns void
language plpgsql security definer set search_path = public as $$
declare v_nid integer; v_n integer;
begin
  if not public.is_app_user() then raise exception 'Nicht autorisiert' using errcode = '42501'; end if;
  select f.notion_fahrer_id into v_nid from public.fahrer f where f.id = p_fahrer_id and f.aktiv;
  if v_nid is null then raise exception 'Fahrer % nicht gefunden oder ohne Notion-Nr.', p_fahrer_id using errcode = 'P0002'; end if;
  select count(*) into v_n from public.fahrer f where f.aktiv and f.notion_fahrer_id = v_nid;
  if v_n <> 1 then raise exception 'Notion-Nr. % ist doppelt vergeben', v_nid using errcode = 'P0001'; end if;
  if p_anbieter = 'bolt' then
    update public.bolt_drivers set fahrer_id = p_fahrer_id, zuordnung_quelle = 'manuell' where driver_uuid = p_driver_uuid;
  else
    update public.uber_drivers set fahrer_id = p_fahrer_id, zuordnung_quelle = 'manuell' where driver_uuid = p_driver_uuid;
  end if;
  if not found then raise exception 'Konto % nicht gefunden', p_driver_uuid using errcode = 'P0002'; end if;
  insert into public.zuordnung_manuell (anbieter, driver_uuid, notion_fahrer_id, gesetzt_von)
  values (p_anbieter, p_driver_uuid, v_nid, coalesce(auth.jwt()->'app_metadata'->>'app_name', 'unbekannt'))
  on conflict (anbieter, driver_uuid) do update set notion_fahrer_id = excluded.notion_fahrer_id;
end $$;

insert into public.fahrer (id, name, telefon, notion_fahrer_id, aktiv) values
  (1, 'Muhammet Usta', '+436605252631', 282, true),
  (2, 'Alt Eintrag', '+436761111111', 50, false);
alter table public.fahrer alter column id restart with 100;
insert into public.notion_fahrer values
  ('p115', 115, 'Ossama Eid', '06766182006', 'Angemeldet', 'LOGA9'),
  ('p265', 265, 'Zahra Houshangpanah', '6643460000', null, null),
  ('p295', 295, 'Zahra Houshangpanah', '+43 664 3460000', null, null),
  ('p298', 298, 'Davoud Haghnejad', null, null, null),
  ('p282', 282, 'Muhammet Usta', '06605252631', null, null),
  ('p50',  50,  'Alt Eintrag', '06761111111', null, null),
  ('p117', 117, 'Mustafa Weg', null, 'Abgemeldet', null),
  ('p300', 300, 'Usta Muhammet', '0699000000', null, null);
insert into public.bolt_drivers (driver_uuid) values ('b-ossama'), ('b-zahra'), ('b-x');
insert into public.uber_drivers (driver_uuid) values ('u-ossama'), ('u-davoud');
`);
await db.exec(readFileSync(new URL('../migrations/2026-10-12-fahrer-aus-notion.sql', import.meta.url), 'utf8'));

const alsBuero = `select set_config('request.jwt.claims', '{"app_metadata":{"app_role":"user","app_name":"Stefan"}}', false)`;
const alsFahrer = `select set_config('request.jwt.claims', '{"app_metadata":{}}', false)`;
const q = async (sql, p) => (await db.query(sql, p)).rows;
const anlegen = (a) => q('select public.konto_fahrer_anlegen($1,$2,$3,$4,$5,$6) as id', a);
const scheitert = async (a, muster) => {
  await assert.rejects(anlegen(a), (e) => { assert.match(e.message, muster); return true; });
};

try {
  // Auswahl: ohne aktiven Eintrag und nicht abgemeldet. Usta (aktiv) fehlt, der inaktive Alt-Eintrag steht drin.
  const liste = (await q('select notion_fahrer_id from public.notion_fahrer_ohne_eintrag order by 1')).map((r) => r.notion_fahrer_id);
  assert.deepEqual(liste, [50, 115, 265, 295, 298, 300]);

  await db.exec(alsFahrer);
  await scheitert(['bolt', 'b-ossama', 115, 'f12', 500, 'W-7235TX'], /Nicht autorisiert/);
  await db.exec(alsBuero);

  // Pflichtfelder
  await scheitert(['bolt', 'b-ossama', 115, null, 500, 'W-7235TX'], /Mietmodell fehlt/);
  await scheitert(['bolt', 'b-ossama', 115, 'f13', 500, 'W-7235TX'], /Mietmodell fehlt/);
  await scheitert(['bolt', 'b-ossama', 115, 'f12', null, 'W-7235TX'], /Pauschale fehlt/);
  await scheitert(['bolt', 'b-ossama', 115, 'f12', -1, 'W-7235TX'], /Pauschale fehlt/);
  await scheitert(['bolt', 'b-ossama', 115, 'f12', 500, '  '], /Kennzeichen fehlt/);
  await scheitert(['bolt', 'b-ossama', 999, 'f12', 500, 'W-7235TX'], /nicht gefunden/);

  // Anlegen + zuordnen: Telefon wird +43…, Satz/Schwelle folgen dem Modell
  const [{ id }] = await anlegen(['bolt', 'b-ossama', 115, 'f12', 500, ' W-7235TX ']);
  const [f] = await q('select * from public.fahrer where id = $1', [id]);
  assert.equal(f.name, 'Ossama Eid'); assert.equal(f.telefon, '+436766182006'); assert.equal(f.kennzeichen, 'W-7235TX');
  assert.equal(f.mietmodell, 'f12'); assert.equal(Number(f.basis_miete), 500);
  assert.equal(Number(f.prozent_satz), 10); assert.equal(Number(f.prozent_schwelle), 1200);
  assert.equal(f.aktiv, true); assert.equal(f.notion_fahrer_id, 115);
  const [b] = await q(`select * from public.bolt_drivers where driver_uuid = 'b-ossama'`);
  assert.equal(b.fahrer_id, id); assert.equal(b.zuordnung_quelle, 'manuell');
  const [z] = await q(`select * from public.zuordnung_manuell where driver_uuid = 'b-ossama'`);
  assert.equal(z.notion_fahrer_id, 115); assert.equal(z.gesetzt_von, 'Stefan');

  // Zweites Konto derselben Person: nicht noch einmal anlegen
  await scheitert(['uber', 'u-ossama', 115, 'f12', 500, 'W-7235TX'], /gibt es schon: Ossama Eid/);

  // Doppelte Notion-Seite (gleiche Nummer bzw. gleicher Name): nur einmal anlegbar
  const [{ id: zid }] = await anlegen(['bolt', 'b-zahra', 295, 'f11', 450, 'W-4181TX']);
  const [fz] = await q('select telefon, prozent_schwelle from public.fahrer where id = $1', [zid]);
  assert.equal(fz.telefon, '+436643460000'); assert.equal(Number(fz.prozent_schwelle), 1100);
  await scheitert(['bolt', 'b-x', 265, 'f11', 450, 'W-4181TX'], /gibt es schon: Zahra Houshangpanah/);

  // Gleicher Name wie ein aktiver Fahrer, andere Notion-Nr. (Wortreihenfolge egal)
  await scheitert(['bolt', 'b-x', 300, 'f12', 500, 'W-1TX'], /gibt es schon: Muhammet Usta/);

  // Ohne Telefon, Modell fix; unbekanntes Konto rollt den neuen Fahrer wieder zurueck
  const vorher = (await q('select count(*)::int n from public.fahrer'))[0].n;
  await scheitert(['uber', 'u-gibtsnicht', 298, 'fix', 300, 'W-1061TX'], /Konto u-gibtsnicht nicht gefunden/);
  assert.equal((await q('select count(*)::int n from public.fahrer'))[0].n, vorher);
  const [{ id: did }] = await anlegen(['uber', 'u-davoud', 298, 'fix', 300, 'W-1061TX']);
  const [fd] = await q('select telefon, prozent_satz, prozent_schwelle from public.fahrer where id = $1', [did]);
  assert.equal(fd.telefon, null); assert.equal(Number(fd.prozent_satz), 0); assert.equal(Number(fd.prozent_schwelle), 0);

  const rest = (await q('select notion_fahrer_id from public.notion_fahrer_ohne_eintrag order by 1')).map((r) => r.notion_fahrer_id);
  assert.deepEqual(rest, [50, 265, 300]);
  console.log('OK');
} catch (e) {
  console.error('FEHLER: ' + (e && e.message || e));
  process.exit(1);
}
